func (p *Provider) runImage(ctx context.Context, op *operation, kind string, req wire.ImageRequest, inputs map[string]resolvedImageInput, commits []ContentCommitter, headers map[string]string) {
	defer p.runs.Done()
	defer close(op.finished)
	defer op.cancel()
	emitProgress := func(percent int64, message string) {
		if percent < 0 || percent > 100 || len(message) > 4096 || !utf8.ValidString(message) {
			return
		}
		op.emit(wire.Delta{Kind: wire.DeltaKindImageProgress, ImageProgress: &wire.ImageProgress{Percent: percent, Message: message}}, p.cfg.Now())
	}
	var end wire.ImageReply
	if kind == "remote" {
		end = p.runRemoteImage(ctx, op, req)
	} else {
		bounds := imageOutputBounds{each: p.cfg.MaxGeneratedImageBytes, total: p.cfg.MaxImageOutputBytes}
		backend := runImageBackend(ctx, p.cfg.HTTP, op.host, op.model, kind, req, inputs, headers, bounds, emitProgress)
		if backend.outcome == wire.ReplyOutcomeCompleted {
			emitProgress(100, "completed")
		}
		end = p.publishImages(ctx, op, req, backend, commits)
	}
	clear(headers)
	if reason := op.stopped(); reason != "" {
		end.Outcome, end.Reason = wire.ReplyOutcomeCancelled, reason
	} else if p.ctx.Err() != nil || ctx.Err() != nil && end.Outcome == wire.ReplyOutcomeUnavailable {
		end.Outcome, end.Reason = wire.ReplyOutcomeCancelled, "caller"
	}
	end.Host, end.Model = op.host.Name, op.model
	if op.credential != "" && p.cfg.Ceilings != nil && !op.remote {
		var micros int64
		if end.Cost != nil {
			micros = end.Cost.Micros
		}
		if err := p.cfg.Ceilings.AddModalities(op.credential, end.Usage.Input+end.Usage.Output, micros, end.Images, 0, 0); err != nil {
			p.report(err)
		}
	}
	now := p.cfg.Now()
	op.emit(wire.Delta{Kind: wire.DeltaKindEnd, ImageEnd: &end}, now)
	record := Record{Operation: op.id, Profile: router.ProfileImage, Route: op.route.name, Rung: op.route.rung, Account: op.subject.Account, Program: op.subject.Program,
		Host: op.host.Name, Model: op.model, Family: familyOf(op.model), Credential: op.credential, Outcome: end.Outcome.String(), Reason: end.Reason,
		TokensIn: end.Usage.Input, TokensOut: end.Usage.Output, Images: end.Images, WallMS: now.Sub(op.started).Milliseconds(), Domain: op.route.domain, Claim: op.route.claim}
	if op.remote {
		record.Domain = op.host.Domain
	}
	if op.credential != "" && p.cfg.Ceilings != nil && !op.remote {
		record.Ceiling = p.cfg.Ceilings.State(op.credential)
	}
	p.record(record)
}

func (p *Provider) publishImages(ctx context.Context, op *operation, req wire.ImageRequest, backend imageBackendReply, commits []ContentCommitter) wire.ImageReply {
	end := wire.ImageReply{Outcome: backend.outcome, Reason: backend.reason, Usage: backend.usage, Cost: backend.cost, Deliveries: []wire.Delivery{}, Images: int64(len(backend.images))}
	if backend.outcome != wire.ReplyOutcomeCompleted {
		return end
	}
	if int64(len(backend.images)) != req.Count || len(commits) != len(backend.images) {
		return wire.ImageReply{Outcome: wire.ReplyOutcomeUnavailable, Reason: "upstream:count", Images: int64(len(backend.images)), Usage: backend.usage, Cost: backend.cost, Deliveries: []wire.Delivery{}}
	}
	var total int64
	for _, output := range backend.images {
		if !generatedInputMedia(output.mediaType) || len(output.data) == 0 || int64(len(output.data)) > p.cfg.MaxGeneratedImageBytes || int64(len(output.data)) > p.cfg.MaxImageOutputBytes-total || http.DetectContentType(output.data) != output.mediaType {
			return wire.ImageReply{Outcome: wire.ReplyOutcomeUnavailable, Reason: "upstream:image", Images: int64(len(backend.images)), Usage: backend.usage, Cost: backend.cost, Deliveries: []wire.Delivery{}}
		}
		total += int64(len(output.data))
	}
	if !op.beginCompletion() {
		return wire.ImageReply{Outcome: wire.ReplyOutcomeCancelled, Reason: "cancel", Images: int64(len(backend.images)), Usage: backend.usage, Cost: backend.cost, Deliveries: []wire.Delivery{}}
	}
	for index, output := range backend.images {
		sum := sha256.Sum256(output.data)
		digest := "sha256:" + hex.EncodeToString(sum[:])
		switch commits[index](ctx, digest, output.data) {
		case ContentResolved:
		case ContentForbidden:
			return wire.ImageReply{Outcome: wire.ReplyOutcomeForbidden, Reason: "output:forbidden", Images: int64(len(backend.images)), Usage: backend.usage, Cost: backend.cost, Deliveries: []wire.Delivery{}}
		default:
			return wire.ImageReply{Outcome: wire.ReplyOutcomeUnavailable, Reason: "output:unavailable", Images: int64(len(backend.images)), Usage: backend.usage, Cost: backend.cost, Deliveries: []wire.Delivery{}}
		}
		delivery := wire.Delivery{Digest: digest, MediaType: output.mediaType, Size: int64(len(output.data)), Location: "local"}
		end.Deliveries = append(end.Deliveries, delivery)
		op.emit(wire.Delta{Kind: wire.DeltaKindImageResult, ImageResult: &wire.ImageResult{Index: int64(index), Delivery: delivery}}, p.cfg.Now())
	}
	return end
}

func imageFailure(outcome wire.ReplyOutcome, reason string) wire.ImageReply {
	return wire.ImageReply{Outcome: outcome, Reason: reason, Deliveries: []wire.Delivery{}}
}

func validateRemoteImageDelivery(req wire.ImageRequest, results []wire.ImageResult, end wire.ImageReply) string {
	if int64(len(results)) != req.Count || len(end.Deliveries) != len(results) || end.Images != int64(len(results)) {
		return "remote:count"
	}
	for i, result := range results {
		if result.Index != int64(i) || result.Delivery != end.Deliveries[i] || !canonicalSHA256(result.Delivery.Digest) || !generatedInputMedia(result.Delivery.MediaType) || result.Delivery.Size < 1 || result.Delivery.Location != "local" {
			return "remote:delivery"
		}
	}
	return ""
}

func remoteImageDeltaShape(delta wire.Delta) string {
	n := 0
	for _, present := range []bool{delta.Part != nil, delta.Usage != nil, delta.End != nil, delta.Segment != nil, delta.TranscriptionEnd != nil, delta.Audio != nil,
		delta.SpeechEnd != nil, delta.Transcript != nil, delta.LiveEnd != nil, delta.ImageProgress != nil, delta.ImageResult != nil, delta.ImageEnd != nil} {
		if present {
			n++
		}
	}
	if n != 1 {
		return "remote:page"
	}
	switch delta.Kind {
	case wire.DeltaKindImageProgress:
		if delta.ImageProgress == nil || delta.ImageProgress.Percent < 0 || delta.ImageProgress.Percent > 100 || len(delta.ImageProgress.Message) > 4096 || !utf8.ValidString(delta.ImageProgress.Message) {
			return "remote:progress"
		}
	case wire.DeltaKindImageResult:
		if delta.ImageResult == nil {
			return "remote:page"
		}
	case wire.DeltaKindEnd:
		if delta.ImageEnd == nil {
			return "remote:terminal"
		}
	default:
		return "remote:page"
	}
	return ""
}

func validateRemoteImageTerminal(req wire.ImageRequest, results []wire.ImageResult, end wire.ImageReply) string {
	if !end.Outcome.Known() {
		return "remote:terminal"
	}
	if end.Outcome == wire.ReplyOutcomeCompleted {
		return validateRemoteImageDelivery(req, results, end)
	}
	if len(results) != 0 || len(end.Deliveries) != 0 || end.Images != 0 {
		return "remote:terminal"
	}
	return ""
}

func validateRemoteImagePage(page wire.DeltaPage, cursor int64) string {
	if cursor < 0 || len(page.Deltas) > 256 || cursor > math.MaxInt64-int64(len(page.Deltas)) || page.Next != cursor+int64(len(page.Deltas)) {
		return "remote:page"
	}
	for i, delta := range page.Deltas {
		if delta.Sequence != cursor+int64(i) {
			return "remote:page"
		}
		if delta.ImageEnd != nil && (i != len(page.Deltas)-1 || !page.AtEnd) {
			return "remote:terminal"
		}
	}
	return ""
}

func (p *Provider) runRemoteImage(ctx context.Context, op *operation, req wire.ImageRequest) wire.ImageReply {
	transport, ok := op.host.RemoteTransport()
	if !ok {
		return imageFailure(wire.ReplyOutcomeUnavailable, "remote:transport")
	}
	forwarded := req
	forwarded.Model = op.model
	forwarded.Extensions = cloneStrings(req.Extensions)
	if forwarded.Extensions == nil {
		forwarded.Extensions = map[string]string{}
	}
	forwarded.Extensions[ClaimExtension] = op.subject.Program
	client := wire.NewImageClient(transport.WithContext(ctx))
	admission, err := client.Start(forwarded)
	if err != nil {
		return imageFailure(wire.ReplyOutcomeUnavailable, "remote:unreachable")
	}
	if admission.Outcome != wire.StartOutcomeAccepted {
		outcome := replyFromStart(admission.Outcome)
		if !outcome.Known() {
			outcome = wire.ReplyOutcomeUnavailable
		}
		return imageFailure(outcome, "remote:"+admission.Reason)
	}
	cancelRemote := func() {
		stop, done := context.WithTimeout(context.Background(), 5*time.Second)
		defer done()
		_, _ = wire.NewImageClient(transport.WithContext(stop)).Cancel(admission.Operation)
	}
	var results []wire.ImageResult
	for cursor := int64(0); ; {
		page, err := client.Observe(admission.Operation, cursor, 256, 65536, remoteObserveWaitMS)
		if ctx.Err() != nil {
			cancelRemote()
			return imageFailure(wire.ReplyOutcomeCancelled, "caller")
		}
		if err != nil || page.Outcome != wire.PageOutcomePage {
			cancelRemote()
			return imageFailure(wire.ReplyOutcomeUnavailable, "remote:unreachable")
		}
		if reason := validateRemoteImagePage(page, cursor); reason != "" {
			cancelRemote()
			return imageFailure(wire.ReplyOutcomeUnavailable, reason)
		}
		for _, delta := range page.Deltas {
			if reason := remoteImageDeltaShape(delta); reason != "" {
				cancelRemote()
				return imageFailure(wire.ReplyOutcomeUnavailable, reason)
			}
			switch delta.Kind {
			case wire.DeltaKindImageProgress:
				progress := *delta.ImageProgress
				op.emit(wire.Delta{Kind: wire.DeltaKindImageProgress, ImageProgress: &progress}, p.cfg.Now())
			case wire.DeltaKindImageResult:
				result := *delta.ImageResult
				if int64(len(results)) >= req.Count || result.Index != int64(len(results)) || !canonicalSHA256(result.Delivery.Digest) || !generatedInputMedia(result.Delivery.MediaType) || result.Delivery.Size < 1 || result.Delivery.Location != "local" {
					cancelRemote()
					return imageFailure(wire.ReplyOutcomeUnavailable, "remote:delivery")
				}
				results = append(results, result)
			case wire.DeltaKindEnd:
				end := *delta.ImageEnd
				if reason := validateRemoteImageTerminal(req, results, end); reason != "" {
					cancelRemote()
					return imageFailure(wire.ReplyOutcomeUnavailable, reason)
				}
				if end.Outcome == wire.ReplyOutcomeCompleted {
					if !op.beginCompletion() {
						cancelRemote()
						return imageFailure(wire.ReplyOutcomeCancelled, "cancel")
					}
					for i := range end.Deliveries {
						end.Deliveries[i].Location = op.host.Domain
						results[i].Delivery.Location = op.host.Domain
						result := results[i]
						op.emit(wire.Delta{Kind: wire.DeltaKindImageResult, ImageResult: &result}, p.cfg.Now())
					}
				}
				return end
			}
		}
		if page.AtEnd {
			cancelRemote()
			return imageFailure(wire.ReplyOutcomeUnavailable, "remote:terminal")
		}
		if len(page.Deltas) == 0 && !waitImagePoll(ctx, minimumImagePollDelay) {
			cancelRemote()
			return imageFailure(wire.ReplyOutcomeCancelled, "caller")
		}
		cursor = page.Next
	}
}
