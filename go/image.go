type localImageDeliveryContextKey struct{}

// WithLocalImageDelivery requires StartImage to choose a host whose completed
// delivery can be read from this service's content store. Compatibility
// gateways use this when their response format contains the generated bytes.
func WithLocalImageDelivery(ctx context.Context) context.Context {
	return context.WithValue(ctx, localImageDeliveryContextKey{}, true)
}

func localImageDeliveryRequired(ctx context.Context) bool {
	required, _ := ctx.Value(localImageDeliveryContextKey{}).(bool)
	return required
}

